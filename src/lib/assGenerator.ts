import { CaptionProject } from '../types';

/**
 * Converts a hex color (#RRGGBB) to ASS color format (&H00BBGGRR&)
 */
export function hexToAssColor(hex: string, alpha = '00'): string {
  const cleanHex = hex.replace('#', '');
  if (cleanHex.length === 6) {
    const r = cleanHex.substring(0, 2);
    const g = cleanHex.substring(2, 4);
    const b = cleanHex.substring(4, 6);
    return `&H${alpha}${b}${g}${r}&`;
  }
  return '&H00FFFFFF&';
}

/**
 * Formats seconds into ASS time format: H:MM:SS.cs
 */
export function formatAssTime(seconds: number): string {
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  let centiseconds = Math.floor(Math.round((seconds % 1) * 100));

  if (centiseconds >= 100) {
    centiseconds = 99;
  }

  return `${hours}:${minutes.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}.${centiseconds.toString().padStart(2, '0')}`;
}

export interface AssGeneratorOptions {
  enablePopAnimation?: boolean; // {\fscx0\fscy0\t(0,150,\fscx100\fscy100)}
  videoWidth?: number;
  videoHeight?: number;
  includeWatermark?: boolean;
}

/**
 * Generates an Advanced SubStation Alpha (.ass) subtitle file with Pop-Up / Bounce animations
 */
export function generateAssFile(project: CaptionProject, options: AssGeneratorOptions = {}): string {
  const {
    enablePopAnimation = true,
    videoWidth = 1080,
    videoHeight = 1920,
    includeWatermark = false,
  } = options;

  const isDevanagari = project.font_family.includes('Devanagari');
  const fontName = isDevanagari ? 'Noto Sans Devanagari' : project.font_family || 'Arial Black';

  const baseFontSize = Math.round(project.font_size * 8.5) + 36;
  const primaryColor = hexToAssColor(project.text_color || '#FFFFFF');
  const highlightColor = hexToAssColor(project.highlight_color || '#FF8C1A');
  let outlineColor = '&H00000000&';
  let backColor = '&H00000000&';
  let borderStyle = 1; // 1 = outline, 3 = opaque background box
  let outlineSize = 6;
  let shadowSize = 0;

  if (project.template_id === 'tpl_002') {
    // Magenta shadow
    outlineColor = hexToAssColor('#FF007F');
    shadowSize = 8;
    outlineSize = 4;
  } else if (project.template_id === 'tpl_005') {
    // Neon Cyan border box
    outlineColor = hexToAssColor('#00F5D4');
    backColor = '&H330F0A0A&'; // 80% opacity dark box
    borderStyle = 3;
    outlineSize = 8;
  } else if (project.template_id === 'tpl_001') {
    // Dark Cinematic Winter Box
    outlineColor = hexToAssColor('#415A77');
    backColor = '&H262A1B0D&'; // 85% opacity dark winter blue
    borderStyle = 3;
    outlineSize = 6;
  } else if (project.template_id === 'tpl_004') {
    // Aesthetic Pastel Box
    outlineColor = hexToAssColor('#E8AEB7');
    backColor = '&H66422D2B&'; // 60% opacity pastel box
    borderStyle = 3;
    outlineSize = 6;
  } else if (project.template_id === 'ali_abdaal' || project.template_id === 'modern') {
    backColor = '&H1A1A1A1A&';
    borderStyle = 3;
    outlineSize = 6;
  }

  // Alignment: 5 = middle center (screen center), 2 = bottom center, 8 = top center
  let alignment = 5;
  let marginV = 10;
  if (project.position === 'bottom') {
    alignment = 2;
    marginV = 120;
  } else if (project.position === 'top') {
    alignment = 8;
    marginV = 120;
  }

  const scriptInfo = [
    '[Script Info]',
    '; Script generated by CAPTIVOX - Animated ASS Subtitle Engine',
    `Title: ${project.title || 'Animated Subtitles'}`,
    'ScriptType: v4.00+',
    `PlayResX: ${videoWidth}`,
    `PlayResY: ${videoHeight}`,
    'ScaledBorderAndShadow: yes',
    'WrapStyle: 0',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    `Style: Default,${fontName},${baseFontSize},${primaryColor},${highlightColor},${outlineColor},${backColor},-1,0,0,0,100,100,0,0,${borderStyle},${outlineSize},${shadowSize},${alignment},10,10,${marginV},1`,
    `Style: Watermark,Outfit,24,&H80FFFFFF&,&H80FFFFFF&,&H80000000&,&H00000000,-1,0,0,0,100,100,0,0,1,1.5,0,3,30,30,40,1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  ];

  const dialogueLines: string[] = [];

  project.captions.forEach((seg) => {
    const startTime = formatAssTime(seg.start_time);
    const endTime = formatAssTime(seg.end_time);

    let textContent = seg.text.trim();
    if (project.text_case === 'uppercase') {
      textContent = textContent.toUpperCase();
    } else if (project.text_case === 'lowercase') {
      textContent = textContent.toLowerCase();
    }

    // DYNAMIC ANIMATION TAG GENERATION
    let lineOutput = textContent;
    if (enablePopAnimation) {
      const animStyle = project.animation_style || 'pop_bounce';
      if (animStyle === 'kinetic_3d') {
        lineOutput = `{\\frx28\\fry-14\\t(0,180,\\frx0\\fry0\\fscx110\\fscy110)}${textContent}`;
      } else if (animStyle === 'glitch_shake') {
        lineOutput = `{\\shad5\\1c&H0000FFFF&\\t(0,60,\\shad-4\\1c&H00FF00FF&)\\t(60,120,\\shad2\\1c&H00FFFFFF&)}${textContent}`;
      } else if (animStyle === 'wavy_float') {
        lineOutput = `{\\fscx108\\fscy108\\t(0,250,\\fscx95\\fscy95)\\t(250,500,\\fscx108\\fscy108)}${textContent}`;
      } else if (animStyle === 'neon_pulse') {
        lineOutput = `{\\blur10\\t(0,200,\\blur26)\\t(200,400,\\blur8)}${textContent}`;
      } else if (animStyle === 'fire_shimmer') {
        lineOutput = `{\\fscx100\\fscy100\\1c&H00008CFF&\\t(0,180,\\1c&H0000FFFF&)\\t(180,360,\\1c&H00008CFF&)}${textContent}`;
      } else {
        // Default explosive pop_bounce with overshoot
        lineOutput = `{\\fscx0\\fscy0\\t(0,120,\\fscx125\\fscy125)\\t(120,200,\\fscx100\\fscy100)}${textContent}`;
      }
    }

    dialogueLines.push(`Dialogue: 0,${startTime},${endTime},Default,,0,0,0,,${lineOutput}`);
  });

  // Watermark if applicable
  if (includeWatermark && project.duration > 0) {
    const startTime = formatAssTime(0);
    const endTime = formatAssTime(project.duration);
    dialogueLines.push(`Dialogue: 1,${startTime},${endTime},Watermark,,0,0,0,,Made with CAPTIVOX`);
  }

  return scriptInfo.concat(dialogueLines).join('\n');
}
